"""Builds src/catalogue/data.ts from docs/project-catalogue.md (the source of truth).
Run: python3 scripts/build-catalogue.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
md = (ROOT / "docs" / "project-catalogue.md").read_text()

LIVE = {"Name Light Show": "/play/name-light-show"}
FEATURED = ["Name Light Show", "Invisible Cloak", "Mars Rover Rescue", "Drone Delivery", "Chandrayaan Lander", "Doodle Guesser", "Train Route Finder", "Secret Code Machine"]

projects, level, level_name, cur, field = [], 0, "", None, None
def clean(t):
    return t.strip().strip("*").strip()

for raw in md.splitlines():
    line = raw.rstrip()
    m = re.match(r"^## Level (\d) · (.+)$", line)
    if m:
        level, level_name = int(m.group(1)), m.group(2).strip()
        cur = None
        continue
    if line.startswith("## ") and not line.startswith("## Level"):
        cur = None
        level = 0
        continue
    m = re.match(r"^### (.+?)( ⭐)?$", line)
    if m and level:
        cur = {"name": m.group(1).strip(), "level": level, "levelName": level_name, "hero": bool(m.group(2)),
               "category": "", "sessions": 0, "phone": "", "pitch": "", "build": "", "wow": "", "python": "",
               "steps": [], "hook": "", "needs": ""}
        projects.append(cur)
        field = None
        continue
    if not cur:
        continue
    m = re.match(r"^\*\*Category:\*\* (.+?) · \*\*Sessions:\*\* (\d+) · \*\*Phone:\*\* (.+)$", line)
    if m:
        cur["category"], cur["sessions"], cur["phone"] = m.group(1).strip(), int(m.group(2)), m.group(3).strip()
        continue
    m = re.match(r"^\*\*(Pitch|What they build|Wow moment|Python|Steps|Show-off hook|Needs|Note|Gateway|Data note|Data and naming notes):\*\*\s*(.*)$", line)
    if m:
        key = {"Pitch": "pitch", "What they build": "build", "Wow moment": "wow", "Python": "python", "Steps": "steps",
               "Show-off hook": "hook", "Needs": "needs"}.get(m.group(1))
        field = key
        if key and key != "steps":
            cur[key] = m.group(2).strip().strip("*").strip()
        continue
    m = re.match(r"^\d+\. (.+)$", line)
    if m and field == "steps":
        cur["steps"].append(m.group(1).strip())
        continue
    if m and field == "build":
        cur["build"] = (cur["build"] + " " + m.group(1).strip()).strip()
        continue

def slug(n):
    return re.sub(r"[^a-z0-9]+", "-", n.lower()).strip("-")

for p in projects:
    p["id"] = slug(p["name"])
    p["href"] = LIVE.get(p["name"])
    p["featured"] = p["name"] in FEATURED
    p["phoneFriendly"] = p["phone"].lower().startswith("yes")

out = ("// Generated by scripts/build-catalogue.py from docs/project-catalogue.md. Do not edit by hand.\n"
       "import type { CatalogueProject } from './types';\n\n"
       f"export const CATALOGUE: CatalogueProject[] = {json.dumps(projects, indent=2, ensure_ascii=False)};\n")
(ROOT / "src" / "catalogue" / "data.ts").write_text(out)
print(len(projects), "projects;", sum(p["featured"] for p in projects), "featured;", [p["name"] for p in projects if not p["pitch"] or not p["build"]])
