export function LearnLessons() {
  const [activeLessonId, setActiveLessonId] = useState<string>(LESSONS[0].id);
  const [liveOutput, setLiveOutput] = useState<string | null>(null);

  const status = useRunnerStatus();
  const activeLesson = LESSONS.find((l) => l.id === activeLessonId) || LESSONS[0];

  useRunnerEvents({
    onStdout: (text) => {
      setLiveOutput((prev) => (prev ? prev + text : text));
    },
    onStderr: (text) => {
      setLiveOutput((prev) => (prev ? `${prev}\n[error] ${text}` : `[error] ${text}`));
    },
  });

  const handleRunSample = () => {
    buzz(12);
    setLiveOutput('');
    const runner = getRunner();
    runner.stop();
    setTimeout(() => {
      runner.run(activeLesson.sampleCode);
    }, 60);
  };

  const isBusy = status === 'running' || status === 'waiting-for-input';

  return (
    <div className="acct-page">
      <SiteNav onHome={false} />

      <main className="acct learn-main">
        {/* Header */}
        <header className="home-hello">
          <div>
            <p></p>
            <h1 className="acct-title">Learn Python Lessons</h1>
            <p className="acct-lead">
              Clear technical definitions, intuitive analogies, mascot tips, and runnable examples for every core Python concept.
            </p>
          </div>
          <div className="home-cast" aria-hidden="true">
            <MascotImg who="riff" pose="pointing" />
            <MascotImg who="nix" pose="welcome" />
          </div>
        </header>

        {/* Lesson View: Sidebar navigation + Main lesson card */}
        <div className="learn-layout">
          {/* Topics List Navigation */}
          <nav className="learn-nav" aria-label="Lessons List">
            <span className="label">Python Topics</span>
            <div className="learn-topic-list">
              {LESSONS.map((l, idx) => (
                <button
                  key={l.id}
                  type="button"
                  className={`learn-topic-btn${activeLessonId === l.id ? ' is-active' : ''}`}
                  onClick={() => {
                    buzz(8);
                    setActiveLessonId(l.id);
                    setLiveOutput(null);
                  }}
                >
                  <span className="learn-topic-no">{String(idx + 1).padStart(2, '0')}</span>
                  <span className="learn-topic-title">{l.topic}</span>
                </button>
              ))}
            </div>
          </nav>

          {/* Detailed Lesson Card */}
          <article className="learn-card">
            <div className="learn-card-head">
              <span className="learn-badge-pill">{activeLesson.badge}</span>
              <h2 className="learn-heading">{activeLesson.topic}</h2>
            </div>

            {/* 1. Technical Definition */}
            <section className="learn-section">
              <div className="learn-section-title">
                <span className="learn-dot" />
                <h3 className="learn-subtitle">Technical Definition</h3>
              </div>
              <p className="learn-text learn-tech-def">{activeLesson.technicalDefinition}</p>
            </section>

            {/* 2. Analogy & Real-world Example */}
            <section className="learn-section">
              <div className="learn-section-title">
                <span className="learn-dot" />
                <h3 className="learn-subtitle">How to picture it (Analogy)</h3>
              </div>
              <p className="learn-text learn-analogy">{activeLesson.analogy}</p>
            </section>

            {/* 3. Mascot Tip Callout */}
            <div className="learn-mascot-callout">
              <div className="learn-mascot-img-wrap" aria-hidden="true">
                <MascotImg who={activeLesson.mascotTip.who} pose={activeLesson.mascotTip.pose} />
              </div>
              <div className="learn-mascot-text">
                <span className="learn-mascot-name">
                  {activeLesson.mascotTip.who === 'nix' ? 'Nix says:' : 'Riff says:'}
                </span>
                <p className="learn-mascot-bubble">{activeLesson.mascotTip.tip}</p>
              </div>
            </div>

            {/* 4. Interactive Runnable Code Box */}
            <section className="learn-section">
              <div className="learn-section-title">
                <span className="learn-dot" />
                <h3 className="learn-subtitle">Interactive Code Example</h3>
              </div>

              <div className="learn-code-box">
                <div className="learn-code-header">
                  <span className="label">main.py</span>
                  <button
                    type="button"
                    className="led-btn led-btn-sm"
                    disabled={isBusy}
                    onClick={handleRunSample}
                  >
                    {isBusy ? 'Running…' : 'Run Example ▶'}
                  </button>
                </div>
                <pre className="learn-code-pre">
                  <code>{activeLesson.sampleCode}</code>
                </pre>

                {/* Output Area */}
                <div className="learn-output-wrap">
                  <span className="label">Screen Output:</span>
                  <pre className="learn-output-pre">
                    <code>{liveOutput !== null ? liveOutput || '(No output produced)' : activeLesson.sampleOutput}</code>
                  </pre>
                </div>
              </div>
            </section>
          </article>
        </div>
      </main>
    </div>
  );
}
